//! lsd color theme
//!
//! See: <https://github.com/lsd-rs/lsd/blob/main/doc/colors.md>
//!
//! One `colors.yaml` per variant, so configure the path as e.g.
//! `extras/lsd/{slug}/colors.yaml`. lsd's theme covers metadata only; file-type
//! colors come from `LS_COLORS`.

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use super::listing::Listing;
use crate::color::Color;
use crate::theme::{Family, Variant};

pub struct Lsd;

impl Renderer for Lsd {
    fn name(&self) -> &'static str {
        "lsd"
    }

    fn render(&self, _family: &Family, variants: &[Variant]) -> Result<String> {
        let [v] = variants else {
            bail!("an lsd theme holds one variant; put `{{slug}}` in its output path");
        };
        let l = Listing::new(v);
        let mut out = format!("# {}: generated by themegen; do not edit.\n", v.name);
        let top =
            |out: &mut String, key: &str, c: Color| writeln!(out, "{key}: \"{}\"", c.hex_rgb());

        top(&mut out, "user", l.you)?;
        top(&mut out, "group", l.muted)?;
        let sections: &[(&str, &[(&str, Color)])] = &[
            (
                "permission",
                &[
                    ("read", l.read),
                    ("write", l.write),
                    ("exec", l.exec),
                    ("exec-sticky", l.special_perm),
                    ("no-access", l.muted),
                    ("octal", l.muted),
                    ("acl", l.muted),
                    ("context", l.muted),
                ],
            ),
            (
                "date",
                &[
                    ("hour-old", l.text),
                    ("day-old", l.muted),
                    ("older", l.muted),
                ],
            ),
            (
                "size",
                &[
                    ("none", l.muted),
                    ("small", l.size_small),
                    ("medium", l.size_medium),
                    ("large", l.size_large),
                ],
            ),
            ("inode", &[("valid", l.muted), ("invalid", l.muted)]),
            ("links", &[("valid", l.muted), ("invalid", l.muted)]),
        ];
        for (section, entries) in sections {
            writeln!(out, "{section}:")?;
            for (key, c) in *entries {
                writeln!(out, "  {key}: \"{}\"", c.hex_rgb())?;
            }
        }
        top(&mut out, "tree-edge", l.muted)?;
        writeln!(out, "git-status:")?;
        for (key, c) in [
            ("default", l.muted),
            ("unmodified", l.muted),
            ("ignored", l.ignored),
            ("new-in-index", l.added),
            ("new-in-workdir", l.added),
            ("typechange", l.modified),
            ("deleted", l.deleted),
            ("renamed", l.renamed),
            ("modified", l.modified),
            ("conflicted", l.conflicted),
        ] {
            writeln!(out, "  {key}: \"{}\"", c.hex_rgb())?;
        }
        Ok(out)
    }
}
