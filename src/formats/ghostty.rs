//! Ghostty terminal theme
//!
//! See: <https://ghostty.org/docs/features/theme>
//!
//! One theme per file; the file name is the theme name, so configure the path
//! as e.g. `extras/ghostty/{name}` and copy the files to
//! `~/.config/ghostty/themes/`.

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use crate::theme::{Family, Variant};

pub struct Ghostty;

impl Renderer for Ghostty {
    fn name(&self) -> &'static str {
        "ghostty"
    }

    fn render(&self, _family: &Family, variants: &[Variant]) -> Result<String> {
        let [v] = variants else {
            bail!("a Ghostty theme holds one variant; put `{{name}}` in its output path");
        };
        let t = &v.terminal;
        let mut out = format!("# {}: generated by themegen; do not edit.\n", v.name);
        for (i, c) in t
            .normal
            .colors()
            .iter()
            .chain(&t.bright.colors())
            .enumerate()
        {
            writeln!(out, "palette = {i}={}", c.hex_rgb())?;
        }
        for (key, c) in [
            ("background", t.background),
            ("foreground", t.foreground),
            ("cursor-color", v.ui.accent),
            ("cursor-text", t.background),
            ("selection-background", v.ui.surface.selection),
            ("selection-foreground", t.foreground),
        ] {
            writeln!(out, "{key} = {}", c.hex_rgb())?;
        }
        Ok(out)
    }
}
