//! fish shell theme
//!
//! See: <https://fishshell.com/docs/current/cmds/fish_config.html>
//!
//! One `.theme` file for the whole family, with a `[light]` or `[dark]`
//! section per variant; fish picks the one matching the terminal's background.
//! An `[unknown]` section, for terminals that don't report their background,
//! repeats the dark variant (or the first, if none is dark).

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use crate::color::Color;
use crate::theme::{Appearance, Family, Style, Variant};

pub struct Fish;

impl Renderer for Fish {
    fn name(&self) -> &'static str {
        "fish"
    }

    fn render(&self, family: &Family, variants: &[Variant]) -> Result<String> {
        for appearance in [Appearance::Dark, Appearance::Light] {
            let n = variants
                .iter()
                .filter(|v| v.appearance == appearance)
                .count();
            if n > 1 {
                bail!(
                    "a fish theme holds one {} variant, but the family has {n}; \
                     put `{{slug}}` in the output path to render one file each",
                    appearance.as_str()
                );
            }
        }
        let mut out = format!(
            "# name: '{}'\n# {0}: generated by themegen; do not edit.\n",
            family.name
        );
        let fallback = variants
            .iter()
            .find(|v| v.appearance == Appearance::Dark)
            .or(variants.first());
        let sections = variants
            .iter()
            .map(|v| (v.appearance.as_str(), v))
            .chain(fallback.map(|v| ("unknown", v)));
        for (section, v) in sections {
            writeln!(out, "\n[{section}]")?;
            writeln!(
                out,
                "# preferred_background: {}",
                hex(v.ui.surface.background)
            )?;
            for (key, value) in variables(v) {
                writeln!(out, "{key} {value}")?;
            }
        }
        Ok(out)
    }
}

/// `rrggbb`, the form fish's own themes use.
fn hex(c: Color) -> String {
    c.hex_rgb().trim_start_matches('#').to_lowercase()
}

/// A role's color plus its bold/italic flags.
fn role(s: &Style) -> String {
    let mut v = hex(s.color);
    if s.bold {
        v.push_str(" --bold");
    }
    if s.italic {
        v.push_str(" --italics");
    }
    v
}

fn variables(v: &Variant) -> Vec<(&'static str, String)> {
    let (x, ui) = (&v.syntax, &v.ui);
    let (text, selection) = (hex(ui.text.default), hex(ui.surface.selection));
    vec![
        ("fish_color_normal", text.clone()),
        ("fish_color_command", role(&x.function)),
        ("fish_color_keyword", role(&x.keyword_control)),
        ("fish_color_quote", role(&x.string)),
        ("fish_color_escape", role(&x.string_special)),
        ("fish_color_param", role(&x.variable)),
        ("fish_color_option", role(&x.variable)),
        ("fish_color_operator", role(&x.operator)),
        ("fish_color_redirection", role(&x.constant)),
        ("fish_color_end", role(&x.punctuation)),
        ("fish_color_comment", role(&x.comment)),
        ("fish_color_error", hex(ui.status.error)),
        ("fish_color_autosuggestion", hex(ui.text.placeholder)),
        ("fish_color_valid_path", "--underline".into()),
        ("fish_color_cancel", "--reverse".into()),
        ("fish_color_cwd", hex(x.keyword.color)),
        ("fish_color_cwd_root", hex(ui.status.error)),
        ("fish_color_user", hex(x.function.color)),
        ("fish_color_host", hex(x.ty.color)),
        ("fish_color_host_remote", hex(ui.status.warning)),
        ("fish_color_status", hex(ui.status.error)),
        ("fish_color_history_current", format!("{text} --bold")),
        (
            "fish_color_search_match",
            format!("--background={selection} --bold"),
        ),
        (
            "fish_color_selection",
            format!("{text} --background={selection} --bold"),
        ),
        ("fish_pager_color_completion", text.clone()),
        ("fish_pager_color_description", role(&x.comment)),
        ("fish_pager_color_prefix", "--bold --underline".into()),
        (
            "fish_pager_color_progress",
            format!(
                "{} --background={} --bold",
                hex(ui.surface.background),
                hex(ui.accent)
            ),
        ),
        (
            "fish_pager_color_selected_background",
            format!("--background={selection}"),
        ),
    ]
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    #[test]
    fn one_section_per_appearance() {
        let spec = Path::new(env!("CARGO_MANIFEST_DIR")).join("norde.toml");
        let family = Family::load(&spec).unwrap();
        let out = Fish.render(&family, &family.variants).unwrap();
        assert_eq!(out.matches("\n[dark]\n").count(), 1);
        assert_eq!(out.matches("\n[light]\n").count(), 1);
        assert_eq!(out.matches("\n[unknown]\n").count(), 1);
        assert!(out.starts_with("# name: 'Norde'\n"));
    }
}
