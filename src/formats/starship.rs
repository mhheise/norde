//! Starship prompt
//!
//! See: <https://starship.rs/config/>
//!
//! A complete powerline `starship.toml`, adapted from Starship's Catppuccin
//! Powerline preset. The layout lives in `starship_layout.toml`, with colors
//! named after what they color; this renderer adds one `[palettes.<slug>]`
//! table per variant and selects the first. The icons need a Nerd Font.

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use crate::color::Color;
use crate::theme::{Family, Variant, slug};

const LAYOUT: &str = include_str!("starship_layout.toml");

pub struct Starship;

impl Renderer for Starship {
    fn name(&self) -> &'static str {
        "starship"
    }

    fn render(&self, family: &Family, variants: &[Variant]) -> Result<String> {
        let Some(first) = variants.first() else {
            bail!("no variants to render");
        };
        let names: Vec<String> = variants.iter().map(|v| slug(&v.name)).collect();
        let mut out = format!(
            "# {}: generated by themegen; do not edit.\n\
             #\n\
             # Set `palette` below to one of: {}.\n\n",
            family.name,
            names.join(", ")
        );
        out.push_str(&LAYOUT.replace("{palette}", &slug(&first.name)));
        for (v, name) in variants.iter().zip(&names) {
            writeln!(out, "\n[palettes.{name}]")?;
            for (key, color) in palette(v) {
                writeln!(out, "{key} = \"{}\"", color.hex_rgb())?;
            }
        }
        Ok(out)
    }
}

/// Palette entries the layout refers to, by segment or symbol.
///
/// Segment backgrounds are syntax hues, which the spec already keeps at WCAG-AA
/// contrast against the editor background, so `segment_text` (that background)
/// stays readable on every segment.
fn palette(v: &Variant) -> [(&'static str, Color); 11] {
    let (x, ui) = (&v.syntax, &v.ui);
    [
        ("os", x.constant.color),
        ("directory", x.string.color),
        ("git", x.function.color),
        ("language", x.ty.color),
        ("environment", x.keyword.color),
        ("time", ui.text.muted),
        ("segment_text", ui.surface.background),
        ("success", ui.status.success),
        ("error", ui.status.error),
        ("replace", x.constant.color),
        ("visual", ui.status.warning),
    ]
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;
    use std::path::Path;

    use toml::Table;

    use super::*;

    fn family() -> Family {
        Family::load(&Path::new(env!("CARGO_MANIFEST_DIR")).join("norde.toml")).unwrap()
    }

    /// Color names the layout uses in `bg:`/`fg:` styles and `[...](name)`.
    fn used_colors() -> BTreeSet<String> {
        let mut names = BTreeSet::new();
        let word = |s: &str| -> String {
            s.chars()
                .take_while(|c| c.is_ascii_lowercase() || *c == '_')
                .collect()
        };
        for prefix in ["bg:", "fg:", "]("] {
            for (i, _) in LAYOUT.match_indices(prefix) {
                let name = word(&LAYOUT[i + prefix.len()..]);
                let closed = LAYOUT[i + prefix.len() + name.len()..].starts_with(')');
                if !name.is_empty() && (prefix != "](" || closed) {
                    names.insert(name);
                }
            }
        }
        names
    }

    #[test]
    fn output_is_valid_toml_with_a_palette_per_variant() {
        let f = family();
        let out = Starship.render(&f, &f.variants).unwrap();
        let t: Table = out.parse().unwrap();
        assert_eq!(t["palette"].as_str(), Some("norde"));
        let palettes = t["palettes"].as_table().unwrap();
        for v in &f.variants {
            assert!(palettes.contains_key(&slug(&v.name)), "{}", v.name);
        }
    }

    #[test]
    fn layout_only_uses_palette_colors() {
        let f = family();
        let defined: BTreeSet<String> = palette(&f.variants[0])
            .iter()
            .map(|(k, _)| (*k).to_owned())
            .collect();
        assert_eq!(used_colors(), defined);
    }

    /// Segment text must stay readable (WCAG-AA) on every segment.
    #[test]
    fn segment_text_is_readable() {
        for v in &family().variants {
            let p = palette(v);
            let text = p.iter().find(|(k, _)| *k == "segment_text").unwrap().1;
            for (key, color) in &p[..6] {
                let ratio = text.contrast(*color);
                assert!(ratio >= 4.5, "{}: {key} is {ratio:.2}:1", v.name);
            }
        }
    }
}
