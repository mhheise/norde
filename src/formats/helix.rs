//! Helix theme
//!
//! See: <https://docs.helix-editor.com/themes.html>
//!
//! One theme per file; Helix names the theme after the file, so configure the
//! path with `{slug}` (e.g. `extras/helix/{slug}.toml`). Every color goes
//! through a `[palette]` entry named after its Norde role or slot, so a theme
//! that `inherits` from this one can override a single role.

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use crate::color::Color;
use crate::theme::{Family, Style, Variant};

pub struct Helix;

/// Palette entries in first-use order; each name maps to exactly one color.
#[derive(Default)]
struct Palette(Vec<(&'static str, Color)>);

impl Palette {
    /// Register `name` for `color` and return the name to reference.
    fn name(&mut self, name: &'static str, color: Color) -> &'static str {
        match self.0.iter().find(|(n, _)| *n == name) {
            Some((_, c)) => assert_eq!(*c, color, "palette name {name:?} reused"),
            None => self.0.push((name, color)),
        }
        name
    }
}

/// One theme key's style. Empty fields defer to Helix's defaults.
#[derive(Default)]
struct Entry {
    fg: Option<&'static str>,
    bg: Option<&'static str>,
    underline: Option<(Option<&'static str>, &'static str)>,
    modifiers: Vec<&'static str>,
}

impl Entry {
    fn fg(fg: &'static str) -> Entry {
        Entry {
            fg: Some(fg),
            ..Entry::default()
        }
    }

    fn bg(bg: &'static str) -> Entry {
        Entry {
            bg: Some(bg),
            ..Entry::default()
        }
    }

    fn fg_bg(fg: &'static str, bg: &'static str) -> Entry {
        Entry {
            fg: Some(fg),
            bg: Some(bg),
            ..Entry::default()
        }
    }

    fn modifiers(modifiers: &[&'static str]) -> Entry {
        Entry {
            modifiers: modifiers.to_vec(),
            ..Entry::default()
        }
    }

    fn with(mut self, modifier: &'static str) -> Entry {
        self.modifiers.push(modifier);
        self
    }

    fn underline(color: Option<&'static str>, style: &'static str) -> Entry {
        Entry {
            underline: Some((color, style)),
            ..Entry::default()
        }
    }

    fn to_toml(&self) -> String {
        if let (Some(fg), None, None, true) =
            (self.fg, self.bg, self.underline, self.modifiers.is_empty())
        {
            return format!("{fg:?}");
        }
        let mut parts = Vec::new();
        if let Some(fg) = self.fg {
            parts.push(format!("fg = {fg:?}"));
        }
        if let Some(bg) = self.bg {
            parts.push(format!("bg = {bg:?}"));
        }
        if let Some((color, style)) = self.underline {
            parts.push(match color {
                Some(c) => format!("underline = {{ color = {c:?}, style = {style:?} }}"),
                None => format!("underline = {{ style = {style:?} }}"),
            });
        }
        if !self.modifiers.is_empty() {
            let mods: Vec<String> = self.modifiers.iter().map(|m| format!("{m:?}")).collect();
            parts.push(format!("modifiers = [{}]", mods.join(", ")));
        }
        format!("{{ {} }}", parts.join(", "))
    }
}

impl Renderer for Helix {
    fn name(&self) -> &'static str {
        "helix"
    }

    fn render(&self, _family: &Family, variants: &[Variant]) -> Result<String> {
        let [v] = variants else {
            bail!("a Helix theme holds one variant; put `{{slug}}` in its output path");
        };
        let mut p = Palette::default();
        let entries = entries(v, &mut p);

        let mut out = format!("# {}: generated by themegen; do not edit.\n\n", v.name);
        for (key, entry) in &entries {
            writeln!(out, "{key:?} = {}", entry.to_toml())?;
        }
        out.push_str("\n[palette]\n");
        for (name, color) in &p.0 {
            writeln!(out, "{name} = \"{}\"", color.hex_rgb())?;
        }
        Ok(out)
    }
}

/// Helix theme keys -> neutral roles and UI slots.
fn entries(v: &Variant, p: &mut Palette) -> Vec<(&'static str, Entry)> {
    let (ui, s, e, t, st, vcs) = (
        &v.ui,
        &v.ui.surface,
        &v.ui.editor,
        &v.ui.text,
        &v.ui.status,
        &v.ui.vcs,
    );
    let x = &v.syntax;

    let background = p.name("background", s.background);
    let panel = p.name("panel", s.panel);
    let active_line = p.name("active_line", s.active_line);
    let border = p.name("border", ui.border.default);
    let text = p.name("text", t.default);
    let placeholder = p.name("placeholder", t.placeholder);
    let line_number = p.name("line_number", e.line_number);
    let line_number_active = p.name("line_number_active", e.line_number_active);
    let selection = p.name("selection", s.selection);
    let accent = p.name("accent", ui.accent);
    let indent_guide = p.name("indent_guide", e.indent_guide);
    let invisible = p.name("invisible", e.invisible);
    let error = p.name("error", st.error);
    let warning = p.name("warning", st.warning);
    let info = p.name("info", st.info);
    let hint = p.name("hint", st.hint);
    let success = p.name("success", st.success);
    let added = p.name("added", vcs.added);
    let deleted = p.name("deleted", vcs.deleted);
    let modified = p.name("modified", vcs.modified);
    let keyword = p.name("keyword", x.keyword.color);
    let constant = p.name("constant", x.constant.color);

    // A syntax role: its color, plus bold/italic as modifiers.
    let mut role = |name: &'static str, style: &Style| {
        let mut entry = Entry::fg(p.name(name, style.color));
        if style.bold {
            entry = entry.with("bold");
        }
        if style.italic {
            entry = entry.with("italic");
        }
        entry
    };

    vec![
        ("ui.background", Entry::bg(background)),
        ("ui.text", Entry::fg(text)),
        ("ui.text.focus", Entry::fg_bg(text, active_line)),
        ("ui.text.inactive", Entry::fg(placeholder)),
        ("ui.virtual", Entry::fg(indent_guide)),
        ("ui.virtual.indent-guide", Entry::fg(indent_guide)),
        ("ui.virtual.whitespace", Entry::fg(invisible)),
        ("ui.virtual.ruler", Entry::bg(active_line)),
        ("ui.virtual.inlay-hint", Entry::fg(placeholder)),
        ("ui.cursor", Entry::fg_bg(background, placeholder)),
        ("ui.cursor.primary", Entry::fg_bg(background, accent)),
        ("ui.cursor.match", Entry::bg(selection).with("bold")),
        ("ui.cursorline.primary", Entry::bg(active_line)),
        ("ui.selection", Entry::bg(selection)),
        ("ui.linenr", Entry::fg(line_number)),
        (
            "ui.linenr.selected",
            Entry::fg(line_number_active).with("bold"),
        ),
        ("ui.statusline", Entry::fg_bg(text, panel)),
        ("ui.statusline.inactive", Entry::fg_bg(placeholder, panel)),
        (
            "ui.statusline.normal",
            Entry::fg_bg(background, keyword).with("bold"),
        ),
        (
            "ui.statusline.insert",
            Entry::fg_bg(background, success).with("bold"),
        ),
        (
            "ui.statusline.select",
            Entry::fg_bg(background, constant).with("bold"),
        ),
        ("ui.bufferline", Entry::fg_bg(placeholder, panel)),
        ("ui.bufferline.active", Entry::fg_bg(text, background)),
        ("ui.popup", Entry::fg_bg(text, panel)),
        ("ui.window", Entry::fg(border)),
        ("ui.help", Entry::fg_bg(text, panel)),
        ("ui.menu", Entry::fg_bg(text, panel)),
        ("ui.menu.selected", Entry::bg(selection)),
        ("ui.menu.scroll", Entry::fg_bg(line_number, panel)),
        ("ui.highlight", Entry::bg(active_line)),
        ("ui.picker.header", Entry::modifiers(&["bold"])),
        ("comment", role("comment", &x.comment)),
        ("keyword", role("keyword", &x.keyword)),
        (
            "keyword.control",
            role("keyword_control", &x.keyword_control),
        ),
        ("keyword.control.import", role("keyword", &x.keyword)),
        ("keyword.operator", role("operator", &x.operator)),
        ("function", role("function", &x.function)),
        ("function.macro", role("macro", &x.r#macro)),
        ("constructor", role("constructor", &x.constructor)),
        ("type", role("type", &x.ty)),
        ("namespace", role("namespace", &x.namespace)),
        ("string", role("string", &x.string)),
        ("string.regexp", role("string_special", &x.string_special)),
        ("string.special", role("string_special", &x.string_special)),
        (
            "constant.character.escape",
            role("string_special", &x.string_special),
        ),
        ("constant", role("constant", &x.constant)),
        ("constant.numeric", role("constant", &x.constant)),
        ("constant.builtin.boolean", role("constant", &x.constant)),
        ("variable", role("variable", &x.variable)),
        (
            "variable.builtin",
            role("variable_special", &x.variable_special),
        ),
        ("variable.other.member", role("property", &x.property)),
        ("attribute", role("attribute", &x.attribute)),
        ("label", role("variable", &x.variable)),
        ("operator", role("operator", &x.operator)),
        ("punctuation", role("punctuation", &x.punctuation)),
        ("tag", role("tag", &x.tag)),
        ("special", role("keyword", &x.keyword)),
        ("markup.heading", role("markup_heading", &x.markup_heading)),
        ("markup.bold", Entry::modifiers(&["bold"])),
        ("markup.italic", Entry::modifiers(&["italic"])),
        ("markup.strikethrough", Entry::modifiers(&["crossed_out"])),
        ("markup.link.url", {
            let mut url = role("markup_link_url", &x.markup_link_url);
            url.underline = Some((None, "line"));
            url
        }),
        (
            "markup.link.text",
            role("markup_link_text", &x.markup_link_text),
        ),
        ("markup.raw", role("markup_raw", &x.markup_raw)),
        ("markup.list", role("punctuation", &x.punctuation)),
        ("markup.quote", role("comment", &x.comment)),
        ("diff.plus", Entry::fg(added)),
        ("diff.minus", Entry::fg(deleted)),
        ("diff.delta", Entry::fg(modified)),
        ("error", Entry::fg(error)),
        ("warning", Entry::fg(warning)),
        ("info", Entry::fg(info)),
        ("hint", Entry::fg(hint)),
        ("diagnostic.error", Entry::underline(Some(error), "curl")),
        (
            "diagnostic.warning",
            Entry::underline(Some(warning), "curl"),
        ),
        ("diagnostic.info", Entry::underline(Some(info), "curl")),
        ("diagnostic.hint", Entry::underline(Some(hint), "curl")),
        ("diagnostic.unnecessary", Entry::modifiers(&["dim"])),
        ("diagnostic.deprecated", Entry::modifiers(&["crossed_out"])),
    ]
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use toml::{Table, Value};

    use super::*;

    fn themes() -> Vec<Table> {
        let spec = Path::new(env!("CARGO_MANIFEST_DIR")).join("norde.toml");
        let family = Family::load(&spec).unwrap();
        family
            .variants
            .iter()
            .map(|v| {
                let out = Helix.render(&family, std::slice::from_ref(v)).unwrap();
                out.parse().unwrap()
            })
            .collect()
    }

    /// Every color a key uses must be defined in `[palette]`.
    #[test]
    fn every_color_is_in_the_palette() {
        fn colors(v: &Value, out: &mut Vec<String>) {
            match v {
                Value::String(s) => out.push(s.clone()),
                Value::Table(t) => {
                    for (k, v) in t {
                        if k != "style" && k != "modifiers" {
                            colors(v, out);
                        }
                    }
                }
                _ => {}
            }
        }
        for theme in themes() {
            let palette = theme["palette"].as_table().unwrap();
            for (key, value) in &theme {
                if key == "palette" {
                    continue;
                }
                let mut used = Vec::new();
                colors(value, &mut used);
                for c in used {
                    assert!(palette.contains_key(&c), "{key}: {c:?} not in palette");
                }
            }
        }
    }

    #[test]
    fn macros_use_the_macro_role() {
        for theme in themes() {
            assert_eq!(theme["function.macro"].as_str(), Some("macro"));
        }
    }

    #[test]
    fn control_flow_is_bold_but_imports_are_not() {
        for theme in themes() {
            assert_eq!(
                theme["keyword.control"]["modifiers"][0].as_str(),
                Some("bold")
            );
            assert_eq!(theme["keyword.control.import"].as_str(), Some("keyword"));
        }
    }
}
