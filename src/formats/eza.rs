//! eza theme
//!
//! See: <https://github.com/eza-community/eza/blob/main/man/eza_colors-explanation.5.md>
//!
//! One `theme.yml` per variant; eza requires that file name, so configure the
//! path as e.g. `extras/eza/{slug}/theme.yml`. Every entry sets its bold and
//! underline explicitly, because eza keeps its own defaults for anything a
//! theme leaves out.

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use super::listing::Listing;
use crate::color::Color;
use crate::theme::{Family, Variant};

pub struct Eza;

/// One styled entry. `None` leaves the foreground to eza.
#[derive(Clone, Copy)]
struct Style {
    fg: Option<Color>,
    bold: bool,
    underline: bool,
}

fn fg(c: Color) -> Style {
    Style {
        fg: Some(c),
        bold: false,
        underline: false,
    }
}

fn bold(c: Color) -> Style {
    Style {
        bold: true,
        ..fg(c)
    }
}

fn underline(c: Color) -> Style {
    Style {
        underline: true,
        ..fg(c)
    }
}

impl Renderer for Eza {
    fn name(&self) -> &'static str {
        "eza"
    }

    fn render(&self, _family: &Family, variants: &[Variant]) -> Result<String> {
        let [v] = variants else {
            bail!("an eza theme holds one variant; put `{{slug}}` in its output path");
        };
        let l = Listing::new(v);
        let mut out = format!("# {}: generated by themegen; do not edit.\n", v.name);

        let sections: &[(&str, &[(&str, Style)])] = &[
            (
                "filekinds",
                &[
                    ("normal", fg(l.text)),
                    ("directory", bold(l.directory)),
                    ("symlink", fg(l.symlink)),
                    ("pipe", fg(l.special)),
                    ("block_device", fg(l.special)),
                    ("char_device", fg(l.special)),
                    ("socket", fg(l.special)),
                    ("special", fg(l.special)),
                    ("executable", bold(l.executable)),
                    ("mount_point", underline(l.directory)),
                ],
            ),
            (
                "perms",
                &[
                    ("user_read", fg(l.read)),
                    ("user_write", fg(l.write)),
                    ("user_execute_file", fg(l.exec)),
                    ("user_execute_other", fg(l.exec)),
                    ("group_read", fg(l.read)),
                    ("group_write", fg(l.write)),
                    ("group_execute", fg(l.exec)),
                    ("other_read", fg(l.read)),
                    ("other_write", fg(l.write)),
                    ("other_execute", fg(l.exec)),
                    ("special_user_file", fg(l.special_perm)),
                    ("special_other", fg(l.special_perm)),
                    ("attribute", fg(l.muted)),
                ],
            ),
            (
                "size",
                &[
                    ("major", fg(l.muted)),
                    ("minor", fg(l.muted)),
                    ("number_byte", fg(l.size_small)),
                    ("number_kilo", fg(l.size_small)),
                    ("number_mega", fg(l.size_medium)),
                    ("number_giga", fg(l.size_large)),
                    ("number_huge", fg(l.size_large)),
                    ("unit_byte", fg(l.muted)),
                    ("unit_kilo", fg(l.muted)),
                    ("unit_mega", fg(l.muted)),
                    ("unit_giga", fg(l.muted)),
                    ("unit_huge", fg(l.muted)),
                ],
            ),
            (
                "users",
                &[
                    ("user_you", fg(l.you)),
                    ("user_root", fg(l.error)),
                    ("user_other", fg(l.text)),
                    ("group_yours", fg(l.you)),
                    ("group_other", fg(l.text)),
                    ("group_root", fg(l.error)),
                ],
            ),
            (
                "links",
                &[("normal", fg(l.muted)), ("multi_link_file", fg(l.special))],
            ),
            (
                "git",
                &[
                    ("new", fg(l.added)),
                    ("modified", fg(l.modified)),
                    ("deleted", fg(l.deleted)),
                    ("renamed", fg(l.renamed)),
                    ("ignored", fg(l.ignored)),
                    ("conflicted", fg(l.conflicted)),
                ],
            ),
            (
                "git_repo",
                &[
                    ("branch_main", fg(l.executable)),
                    ("branch_other", fg(l.special)),
                    ("git_clean", fg(l.added)),
                    ("git_dirty", fg(l.modified)),
                ],
            ),
            (
                "file_type",
                &[
                    ("image", fg(l.media)),
                    ("video", fg(l.media)),
                    ("music", fg(l.media)),
                    ("crypto", fg(l.crypto)),
                    ("document", fg(l.text)),
                    ("compressed", fg(l.archive)),
                    ("temp", fg(l.muted)),
                    ("compiled", fg(l.muted)),
                    ("build", underline(l.build)),
                    ("source", fg(l.text)),
                ],
            ),
        ];
        for (section, entries) in sections {
            writeln!(out, "\n{section}:")?;
            for (key, style) in *entries {
                writeln!(out, "  {key}:")?;
                write_style(&mut out, 4, *style)?;
            }
        }

        let top: &[(&str, Style)] = &[
            ("punctuation", fg(l.muted)),
            ("date", fg(l.muted)),
            ("inode", fg(l.muted)),
            ("blocks", fg(l.muted)),
            ("header", underline(l.text)),
            ("octal", fg(l.muted)),
            ("flags", fg(l.muted)),
            ("control_char", fg(l.error)),
            ("broken_symlink", fg(l.error)),
            (
                "broken_path_overlay",
                Style {
                    fg: None,
                    bold: false,
                    underline: true,
                },
            ),
        ];
        for (key, style) in top {
            writeln!(out, "\n{key}:")?;
            write_style(&mut out, 2, *style)?;
        }
        Ok(out)
    }
}

fn write_style(out: &mut String, indent: usize, s: Style) -> std::fmt::Result {
    let pad = " ".repeat(indent);
    if let Some(c) = s.fg {
        writeln!(out, "{pad}foreground: \"{}\"", c.hex_rgb())?;
    }
    writeln!(out, "{pad}is_bold: {}", s.bold)?;
    writeln!(out, "{pad}is_underline: {}", s.underline)
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    /// Every `foreground` is a quoted hex color, which eza accepts.
    #[test]
    fn foregrounds_are_hex() {
        let spec = Path::new(env!("CARGO_MANIFEST_DIR")).join("norde.toml");
        let family = Family::load(&spec).unwrap();
        for v in &family.variants {
            let out = Eza.render(&family, std::slice::from_ref(v)).unwrap();
            let fgs: Vec<&str> = out
                .lines()
                .filter_map(|l| l.trim().strip_prefix("foreground: "))
                .collect();
            assert!(fgs.len() > 50, "{}", fgs.len());
            for f in fgs {
                assert!(f.starts_with('"') && f.ends_with('"'), "{f}");
                assert!(f.trim_matches('"').parse::<Color>().is_ok(), "{f}");
            }
        }
    }
}
