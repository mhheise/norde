//! `LS_COLORS`, as read by GNU `ls`, lsd, fd, tree, and others
//!
//! See: <https://www.gnu.org/software/coreutils/manual/html_node/dircolors-invocation.html>
//!
//! One shell snippet per variant that exports `LS_COLORS`, so configure the
//! path with `{slug}`. The colors match the eza and lsd themes; file types are
//! matched by name suffix.

use std::fmt::Write;

use anyhow::{Result, bail};

use super::Renderer;
use super::listing::Listing;
use crate::color::Color;
use crate::theme::{Family, Variant};

pub struct LsColors;

const MEDIA: &[&str] = &[
    // images
    "avif", "bmp", "gif", "heic", "ico", "jpeg", "jpg", "png", "psd", "svg", "tif", "tiff", "webp",
    "xcf", // video
    "avi", "flv", "m4v", "mkv", "mov", "mp4", "webm", "wmv", // audio
    "aac", "aiff", "flac", "m4a", "mp3", "ogg", "opus", "wav",
];
const ARCHIVE: &[&str] = &[
    "7z", "bz2", "deb", "dmg", "gz", "iso", "jar", "lz4", "lzma", "rar", "rpm", "tar", "tbz2",
    "tgz", "txz", "xz", "zip", "zst",
];
const CRYPTO: &[&str] = &[
    "asc", "crt", "gpg", "key", "p12", "pem", "pfx", "pgp", "sig",
];
const TEMP: &[&str] = &["bak", "old", "orig", "swo", "swp", "tmp"];
const COMPILED: &[&str] = &[
    "a", "beam", "class", "dll", "dylib", "elc", "o", "obj", "pyc", "pyo", "so",
];
/// Matched as whole names (a suffix match on the name).
const BUILD: &[&str] = &[
    "CMakeLists.txt",
    "Cargo.toml",
    "Makefile",
    "build.gradle",
    "justfile",
    "package.json",
    "pyproject.toml",
];

/// An SGR sequence: optional attributes, then a 24-bit foreground.
fn sgr(attrs: &str, c: Color) -> String {
    let rgb = format!("38;2;{};{};{}", c.r, c.g, c.b);
    if attrs.is_empty() {
        rgb
    } else {
        format!("{attrs};{rgb}")
    }
}

impl Renderer for LsColors {
    fn name(&self) -> &'static str {
        "ls_colors"
    }

    fn render(&self, _family: &Family, variants: &[Variant]) -> Result<String> {
        let [v] = variants else {
            bail!("an LS_COLORS snippet holds one variant; put `{{slug}}` in its output path");
        };
        let value = value(&Listing::new(v));
        Ok(format!(
            "# {}: generated by themegen; do not edit.\nexport LS_COLORS='{value}'\n",
            v.name
        ))
    }
}

fn value(l: &Listing) -> String {
    let mut entries: Vec<(String, String)> = vec![
        ("rs".into(), "0".into()),
        ("no".into(), sgr("", l.text)),
        ("fi".into(), sgr("", l.text)),
        ("di".into(), sgr("1", l.directory)),
        ("ln".into(), sgr("", l.symlink)),
        ("pi".into(), sgr("", l.special)),
        ("so".into(), sgr("", l.special)),
        ("do".into(), sgr("", l.special)),
        ("bd".into(), sgr("", l.special)),
        ("cd".into(), sgr("", l.special)),
        ("or".into(), sgr("", l.error)),
        ("mi".into(), sgr("", l.error)),
        ("su".into(), sgr("", l.special_perm)),
        ("sg".into(), sgr("", l.special_perm)),
        // Directories that others can write to stay directories, underlined.
        ("tw".into(), sgr("1;4", l.directory)),
        ("ow".into(), sgr("1;4", l.directory)),
        ("st".into(), sgr("1", l.directory)),
        ("ex".into(), sgr("1", l.executable)),
    ];
    for (exts, style) in [
        (MEDIA, sgr("", l.media)),
        (ARCHIVE, sgr("", l.archive)),
        (CRYPTO, sgr("", l.crypto)),
        (TEMP, sgr("", l.muted)),
        (COMPILED, sgr("", l.muted)),
    ] {
        for ext in exts {
            entries.push((format!("*.{ext}"), style.clone()));
        }
    }
    entries.push(("*~".into(), sgr("", l.muted)));
    for name in BUILD {
        entries.push((format!("*{name}"), sgr("4", l.build)));
    }
    let mut out = String::new();
    for (i, (key, style)) in entries.iter().enumerate() {
        if i > 0 {
            out.push(':');
        }
        let _ = write!(out, "{key}={style}");
    }
    out
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;
    use std::path::Path;

    use super::*;

    fn values() -> Vec<String> {
        let spec = Path::new(env!("CARGO_MANIFEST_DIR")).join("norde.toml");
        let family = Family::load(&spec).unwrap();
        family
            .variants
            .iter()
            .map(|v| value(&Listing::new(v)))
            .collect()
    }

    /// No key appears twice, and nothing needs shell quoting inside `'…'`.
    #[test]
    fn keys_are_unique_and_quote_safe() {
        for v in values() {
            assert!(!v.contains('\''));
            let mut seen = HashSet::new();
            for entry in v.split(':') {
                let (key, style) = entry.split_once('=').unwrap();
                assert!(seen.insert(key), "duplicate {key}");
                assert!(
                    style.chars().all(|c| c.is_ascii_digit() || c == ';'),
                    "{entry}"
                );
            }
        }
    }
}
